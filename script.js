document.addEventListener('DOMContentLoaded', () => {
    laadStatus();
    laadUpdates();
});

function laadStatus() {
    const statusDiv = document.getElementById('status-display');
    const html = `
        <div class="status-item">
            <div class="status-icon">📍</div> 
            <div><strong>Locatie:</strong><br> ${huidigeStatus.locatie}</div>
        </div>
        <div class="status-item">
            <div class="status-icon">🤞</div>
            <div><strong>Gevoel:</strong><br> ${huidigeStatus.stemming}</div>
        </div>
        <div class="status-item">
            <div class="status-icon">👥</div>
            <div><strong>Bezoek:</strong><br> ${huidigeStatus.bezoek}</div>
        </div>
    `;
    statusDiv.innerHTML = html;
}

function laadUpdates() {
    const timelineDiv = document.getElementById('timeline');
    if (!timelineDiv) return;

    let html = '';

    updates.forEach(update => {
        
        // FOTO LOGICA
        let alleFotos = [];
        if (update.fotos && update.fotos.length > 0) {
            alleFotos = update.fotos;
        } else if (update.fotoUrl) {
            alleFotos = [update.fotoUrl];
        }

        let fotoHtml = '';
        if (alleFotos.length > 0) {
            fotoHtml = '<div class="gallery-grid">'; 
            alleFotos.forEach(url => {
                fotoHtml += `
                    <img src="${url}" 
                         alt="Foto update" 
                         class="gallery-item" 
                         onclick="openLightbox('${url}')"
                         onerror="this.style.display='none'">
                `;
            });
            fotoHtml += '</div>'; 
        }

        // VIDEO LOGICA (Nieuw: video's zitten nu ook in een net grid)
        let alleVideos = [];
        if (update.videos && update.videos.length > 0) {
            alleVideos = update.videos;
        } else if (update.videoUrl) {
            alleVideos = [update.videoUrl];
        }

        let videoHtml = '';
        if (alleVideos.length > 0) {
            videoHtml = '<div class="video-grid">'; // Zelfde soort rooster als de foto's
            alleVideos.forEach(url => {
                videoHtml += `
                    <video controls class="update-video" preload="metadata">
                        <source src="${url}" type="video/mp4">
                        Oeps, je browser ondersteunt het afspelen van deze video niet.
                    </video>
                `;
            });
            videoHtml += '</div>';
        }

        // Tekst opmaak
        let opgemaaktBericht = "";
        if (update.bericht) {
            let metAlineas = update.bericht.replace(/\n\s*\n/g, '<br><br>');
            opgemaaktBericht = metAlineas.replace(/\n/g, ' ');
        }

        html += `
            <div class="update-card">
                <div class="update-header">
                    <span class="update-date">${update.datum}</span>
                    <span class="update-time">${update.tijd}</span>
                </div>
                <div class="update-text">
                    ${opgemaaktBericht}
                </div>
                ${fotoHtml}
                ${videoHtml}
            </div>
        `;
    });

    timelineDiv.innerHTML = html;
}

// Functies voor de grote foto weergave (Lightbox)
function openLightbox(url) {
    const lightbox = document.getElementById('lightbox');
    const lightboxImg = document.getElementById('lightbox-img');
    lightbox.style.display = "block";
    lightboxImg.src = url;
}

function sluitLightbox() {
    document.getElementById('lightbox').style.display = "none";
}








